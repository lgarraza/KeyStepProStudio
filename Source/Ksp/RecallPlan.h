/** The whole plan, flattened: one entry per bulk request, in recall order. */
inline std::vector<Request> expandPlan()
{
    std::vector<Request> out;
    for (const auto& g : groups())
        for (int i = g.lo; i <= g.hi; ++i)
        {
            std::vector<std::vector<std::uint8_t>> paths { {} };
            for (const auto& d : g.dims)
            {
                std::vector<std::vector<std::uint8_t>> next;
                for (const auto& p : paths)
                    for (int x : d)
                    {
                        auto q = p;
                        q.push_back (static_cast<std::uint8_t> (x == kI ? i : x));
                        next.push_back (std::move (q));
                    }
                paths = std::move (next);
            }
            for (const auto& p : paths)
                for (auto prm : g.params)
                    out.push_back ({ g.item, prm, p, g.count });
        }
    return out;
}

